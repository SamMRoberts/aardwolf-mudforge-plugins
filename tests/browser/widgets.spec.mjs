import { test, expect, property, noHorizontalOverflow } from './harness.mjs';

const state = (documents, name, key) => JSON.parse(documents[name].properties[key]);
const lastMessage = page => page.evaluate(() => window.smoke.messages.at(-1));

test('Inventory summary uses keyboard bag access and renders data updates', async ({ page, openWidget, documents }) => {
  await openWidget('inventory-summary');
  await expect(page).toHaveTitle('Aardwolf Inventory');
  await expect(page.locator('#item-count')).toHaveText('6');
  const bag = page.locator('#bags button').first();
  await bag.focus();
  await page.keyboard.press('Enter');
  expect(await lastMessage(page)).toEqual({ event: 'open', data: { scope: 'container:101' } });
  const update = state(documents, 'inventory-summary', 'inventory');
  update.count = 7;
  update.feedback = 'Synthetic inventory update';
  await property(page, 'inventory', update);
  await expect(page.locator('#item-count')).toHaveText('7');
  await expect(bag).toBeFocused();
  await page.locator('#setup-button').focus();
  await page.keyboard.press('Space');
  expect((await lastMessage(page)).event).toBe('setup');
  await noHorizontalOverflow(page);
});

test('Inventory manager preserves search and prompt drafts through updates', async ({ page, openWidget, documents }) => {
  await openWidget('inventory-manager');
  const search = page.locator('#search');
  await search.fill('potion');
  await expect(page.locator('#items tr')).toHaveCount(2);
  const update = state(documents, 'inventory-manager', 'inventory');
  update.entries.push({ ...update.entries[2], id: 301, plainName: 'a green potion' });
  await property(page, 'inventory', update);
  await expect(page.locator('#items tr')).toHaveCount(3);
  await expect(search).toHaveValue('potion');
  await expect(search).toBeFocused();
  const row = page.locator('#items tr').first();
  await row.focus();
  await page.keyboard.press('Enter');
  expect((await lastMessage(page)).event).toBe('select');
  update.prompt = { kind: 'give', itemId: 103, token: 'synthetic-token', title: 'Give item', steps: ['Choose recipient'] };
  await property(page, 'inventory', update);
  const recipient = page.locator('#recipient');
  await expect(recipient).toBeFocused();
  await recipient.fill('2.guard draft');
  update.feedback = 'Unrelated inventory update';
  await property(page, 'inventory', update);
  await expect(recipient).toHaveValue('2.guard draft');
  await expect(recipient).toBeFocused();
  await page.keyboard.press('Enter');
  expect(await lastMessage(page)).toEqual({ event: 'submit', data: {
    kind: 'give', itemId: 103, token: 'synthetic-token', recipient: '2.guard draft',
  } });
  await noHorizontalOverflow(page);
});

test('Inventory setup retains unsaved controls, focus and scroll as bags update', async ({ page, openWidget, documents }) => {
  await openWidget('inventory-setup');
  const name = page.locator('#heal-potion-name');
  await name.fill('healing draft');
  await page.locator('#add-rule').click();
  const rule = page.getByRole('textbox', { name: 'Rule 1 name contains' });
  await rule.fill('unsaved rule');
  const scroll = await page.evaluate(() => document.scrollingElement.scrollTop);
  const update = state(documents, 'inventory-setup', 'inventory');
  update.bags.push({ id: 999, name: 'New bag', plainName: 'New bag', location: 'inventory' });
  update.feedback = 'Synthetic bag discovery';
  await property(page, 'inventory', update);
  await expect(rule).toHaveValue('unsaved rule');
  await expect(rule).toBeFocused();
  await expect(name).toHaveValue('healing draft');
  expect(await page.evaluate(() => document.scrollingElement.scrollTop)).toBe(scroll);
  await expect(page.locator('#heal-potion-bag option[value="999"]')).toHaveCount(1);
  await page.getByRole('button', { name: 'Save setup', exact: true }).focus();
  await page.keyboard.press('Enter');
  const message = await lastMessage(page);
  expect(message.event).toBe('save');
  expect(message.data.profile.quickPotions.heal.name).toBe('healing draft');
  expect(message.data.profile.rules[0].name).toBe('unsaved rule');
  update.saveResult = { serial: 1, ok: false, message: 'Synthetic save refusal; draft retained' };
  await property(page, 'inventory', update);
  await expect(page.locator('#draft-state')).toContainText('draft retained');
  await expect(rule).toHaveValue('unsaved rule');
  await noHorizontalOverflow(page);
});

test('Spells supports keyboard layout editing, stable focus and resize', async ({ page, openWidget, documents }, testInfo) => {
  await openWidget('spells');
  await expect(page).toHaveTitle('Aardwolf Damage Abilities');
  await expect(page.locator('#rows .row')).toHaveCount(20);
  await expect(page.locator('[data-mud-bind="single_bash_name"]')).toHaveText('Sap');
  await page.locator('#edit').focus();
  await page.keyboard.press('Enter');
  expect((await lastMessage(page)).data.operation).toBe('edit');
  const layout = state(documents, 'spells', 'panelLayout');
  layout.editing = true; layout.revision++;
  await property(page, 'panelLayout', layout);
  await expect(page.locator('#edit')).toHaveAttribute('aria-pressed', 'true');
  const handle = page.getByRole('button', { name: 'Move acid', exact: true });
  await handle.focus();
  await page.keyboard.press('Alt+ArrowDown');
  expect((await lastMessage(page)).data).toMatchObject({ operation: 'move', damageType: 'acid', target: 'air', after: true });
  layout.layout.order.splice(0, 2, 'air', 'acid'); layout.revision++;
  await property(page, 'panelLayout', layout);
  await expect(handle).toBeFocused();
  await expect(page.locator('#rows .row').first()).toHaveAttribute('data-type', 'air');
  await page.evaluate(() => window.smoke.bindings({ single_bash_name: 'Updated synthetic ability' }));
  await expect(handle).toBeFocused();
  await expect(page.locator('[data-mud-bind="single_bash_name"]')).toHaveText('Updated synthetic ability');
  await page.setViewportSize({ width: testInfo.project.name === 'narrow' ? 1280 : 260, height: 220 });
  await expect(page.locator('body')).toHaveClass(/compact/);
  await expect(handle).toBeFocused();
  await noHorizontalOverflow(page);
  const toolbar = await page.locator('.toolbar').boundingBox();
  expect(toolbar.y + toolbar.height).toBeLessThanOrEqual(221);
  await page.screenshot({ path: testInfo.outputPath('spells-resized.png') });
});

test('Room Details preserves filter drafts and supports keyboard details and collapse', async ({ page, openWidget, documents }) => {
  await openWidget('room-details');
  await expect(page).toHaveTitle('Room Details');
  await expect(page.locator('#chars button')).toHaveCount(3);
  await expect(page.locator('#chars img')).toHaveCount(0);
  const filter = page.locator('#filter');
  await filter.fill('WHITE AURA');
  await expect(page.locator('#chars-count')).toHaveText('2/3');
  const update = state(documents, 'room-details', 'roomDetails');
  update.status = 'Synthetic partial update'; update.statusVisible = true;
  await property(page, 'roomDetails', update);
  await expect(filter).toHaveValue('WHITE AURA');
  await expect(filter).toBeFocused();
  await page.keyboard.press('Tab');
  await expect(page.locator('#filter-clear')).toBeFocused();
  await page.keyboard.press('Enter');
  await expect(filter).toHaveValue('');
  const second = page.locator('#chars button').nth(1);
  await second.focus();
  await page.keyboard.press('Enter');
  expect((await lastMessage(page)).data).toMatchObject({ kind: 'chars', index: 2 });
  update.selection = { kind: 'chars', index: 2, revision: update.chars.revision };
  await property(page, 'roomDetails', update);
  await page.keyboard.press('Enter');
  await expect(page.locator('#detail-dialog')).toBeVisible();
  await expect(page.locator('#detail-text')).toHaveText('(White Aura) A merchant.');
  await page.keyboard.press('Escape');
  await expect(page.locator('#detail-dialog')).toBeHidden();
  await expect(second).toBeFocused();
  await page.locator('#chars-toggle').focus();
  await page.keyboard.press('Space');
  expect((await lastMessage(page)).data).toEqual({ chars: true, objs: false });
  update.collapsePreferences.chars = true;
  await property(page, 'roomDetails', update);
  await expect(page.locator('#chars')).toBeHidden();
  await expect(page.locator('#objs')).toBeVisible();
  await noHorizontalOverflow(page);
});

test('Vitals renders bound updates and settings retain drafts through live-style updates', async ({ page, openWidget }) => {
  await openWidget('vitals');
  // Vitals supplies an HTML fragment; its widget title belongs to the native host.
  await expect(page).toHaveTitle('');
  await expect(page.locator('.hp .name')).toHaveText('HP');
  await expect(page.locator('[data-mud-bind="hpValues"]')).toHaveText('80 / 100');
  await page.getByRole('button', { name: 'Refresh vitals' }).focus();
  await page.keyboard.press('Enter');
  expect(await lastMessage(page)).toEqual({ event: 'action', data: { action: 'refresh' } });
  await page.evaluate(() => window.smoke.bindings({ hpValues: '25 / 100', hpWidth: '25%', hpLevel: 'warning' }));
  await expect(page.locator('.hp')).toHaveAttribute('data-level', 'warning');
  await expect(page.locator('.hp .fill')).toHaveAttribute('style', /width: 25%/);
  await expect(page.locator('[data-mud-bind="hpValues"]')).toHaveText('25 / 100');
  await noHorizontalOverflow(page);
  await openWidget('vitals-settings');
  const family = page.locator('[name="fontFamily"]');
  await family.fill('monospace draft');
  await page.evaluate(() => window.smoke.bindings({ feedback: 'Synthetic vitals update' }));
  await expect(family).toHaveValue('monospace draft');
  await expect(family).toBeFocused();
  await page.getByRole('button', { name: 'Save settings', exact: true }).focus();
  await page.keyboard.press('Enter');
  expect((await lastMessage(page)).data.formData.fontFamily).toBe('monospace draft');
  await noHorizontalOverflow(page);
});
